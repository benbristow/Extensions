namespace BenBristow.Extensions.Enums;

/// <summary>
/// Specifies the direction for sorting operations.
/// </summary>
public enum SortDirection
{
    /// <summary>
    /// Sort in ascending order (smallest to largest, A to Z).
    /// </summary>
    Ascending = 0,
    
    /// <summary>
    /// Sort in descending order (largest to smallest, Z to A).
    /// </summary>
    Descending = 1
}